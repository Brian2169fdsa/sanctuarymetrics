"""Extract the CP-101 Conditions for Access (pages 2-3) and the signature
declarations (page 4) verbatim from the blank form, for cpao-apply.html.

    python3 tools/build-cpao-text.py cpao/assets/IndividualUserApplicationForm.pdf > cpao/cp101-text.js

Uses pdftotext -layout: headings are centred (indented), each condition
starts at the margin with "I will", and its continuation lines are indented
two spaces. Re-run whenever the form revision changes."""
import json, re, subprocess, sys

pdf = sys.argv[1]

def layout(first, last):
    return subprocess.run(['pdftotext', '-layout', '-f', str(first), '-l', str(last), pdf, '-'],
                          capture_output=True, text=True, check=True).stdout

def blocks(text, stop_at=None):
    out = []
    for line in text.split('\n'):
        if re.search(r'CP-101 \(rev [\d/]+\)\s+Page \d of \d', line) or '\f' in line and not line.strip('\f').strip():
            continue
        raw = line.replace('\f', '')
        s = raw.strip()
        if not s:
            if out and out[-1]['type'] == 'p' and not out[-1].get('closed'):
                out[-1]['closed'] = True
            continue
        if stop_at and s.startswith(stop_at):
            break
        indent = len(raw) - len(raw.lstrip(' '))
        if indent >= 20:
            out.append({'type': 'h', 'text': s})
        elif s.startswith('I will'):
            out.append({'type': 'li', 'text': s})
        elif indent >= 1 and out and out[-1]['type'] == 'li':
            out[-1]['text'] += ' ' + s
        elif out and out[-1]['type'] == 'p' and not out[-1].get('closed'):
            out[-1]['text'] += ' ' + s
        else:
            out.append({'type': 'p', 'text': s})
    for b in out:
        b.pop('closed', None)
        b['text'] = re.sub(r'\s+', ' ', b['text']).strip()
    return out

conditions = blocks(layout(2, 3))
page4 = blocks(layout(4, 4), stop_at=None)
# page 4: keep the two headings and their declaration paragraphs, drop the signature-line labels
decl = [b for b in page4 if b['type'] == 'h' or (b['type'] == 'p' and len(b['text']) > 120)]
user_decl = decl[1]['text'] if len(decl) > 1 else ''
sa_decl = decl[3]['text'] if len(decl) > 3 else ''
print('/* Generated by tools/build-cpao-text.py from the blank CP-101 (rev 12/2024).')
print('   Verbatim text of pages 2-3 (Conditions for Access) and the page 4 declarations. Do not edit by hand. */')
print('var CP101_TEXT = ' + json.dumps({'form_version': 'CP-101 rev 12/2024', 'conditions': conditions,
                                         'user_declaration': user_decl, 'site_admin_declaration': sa_decl},
                                        indent=1, ensure_ascii=False) + ';')
print("if (typeof module !== 'undefined') { module.exports = CP101_TEXT; }")
